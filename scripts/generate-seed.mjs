#!/usr/bin/env node
// Writes supabase/seed.sql from lib/data/mock.ts, so a fresh database previews
// exactly like the mock-data site. SAMPLE DATA: never load it into production.
//
//   node scripts/generate-seed.mjs
//
// Needs Node 23.6+ (imports the TypeScript mock file directly).

import { writeFileSync } from "node:fs"
import { join } from "node:path"
import { pathToFileURL } from "node:url"

const root = process.cwd()
const mock = await import(pathToFileURL(join(root, "lib", "data", "mock.ts")).href)

// jsonb columns are wrapped with J(); bare arrays are text[] columns.
const J = (value) => ({ json: value })
const q = (v) => {
  if (v === null || v === undefined) return "null"
  if (typeof v === "number") return String(v)
  if (typeof v === "boolean") return v ? "true" : "false"
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]"
  if (typeof v === "object" && "json" in v) return v.json === null ? "null" : `${q(JSON.stringify(v.json))}::jsonb`
  return `'${String(v).replace(/'/g, "''")}'`
}

function insert(table, rows, map) {
  if (!rows.length) return ""
  const mapped = rows.map(map)
  const cols = Object.keys(mapped[0])
  const values = mapped.map((r) => `  (${cols.map((c) => q(r[c])).join(", ")})`)
  return `insert into public.${table} (${cols.join(", ")}) values\n${values.join(",\n")};\n\n`
}

let sql = `-- SAMPLE DATA generated by scripts/generate-seed.mjs from lib/data/mock.ts.
-- For local development and previews only. Do NOT run against production.

`
sql += insert("communities", mock.communities, (c) => ({
  slug: c.slug, name: c.name, summary: J(c.summary), lifestyle: J(c.lifestyle), schools: J(c.schools), transport: J(c.transport),
  avg_price_per_sqft: c.avgPricePerSqft, est_yield: c.estYield, price_change_12m: c.priceChange12m,
  lat: c.geo.lat, lng: c.geo.lng, waterfront: c.waterfront, dld_areas: c.dldAreas ?? [], published: true,
}))
sql += insert("developers", mock.developers, (d) => ({
  slug: d.slug, name: d.name, founded: d.founded ?? null, summary: J(d.summary),
  delivered_projects: d.deliveredProjects, on_time_rate: d.onTimeRate, promises_kept: d.promisesKept, published: true,
}))
sql += insert("agents", mock.agents, (a, i) => ({
  slug: a.slug, name: a.name, role: a.role, languages: a.languages, specialties: a.specialties, bio: J(a.bio),
  brn: a.brn, responds_within: a.respondsWithin, active: true, sort_order: i * 10,
}))
sql += insert("projects", mock.projects, (p) => ({
  slug: p.slug, name: p.name, developer_slug: p.developerSlug, community_slug: p.communitySlug, summary: J(p.summary),
  launch_price_aed: p.launchPriceAed, handover: p.handover, payment_plan: J(p.paymentPlan), unit_types: p.unitTypes,
  construction_progress: p.constructionProgress, escrow_registered: p.escrowRegistered, lat: p.geo.lat, lng: p.geo.lng, published: true,
  floors: p.floors ?? null, launched_on: p.launchedOn ?? null,
}))
sql += insert("properties", mock.properties, (p) => ({
  slug: p.slug, title: J(p.title), description: J(p.description), status: p.status, listing: p.listing, type: p.type,
  community_slug: p.communitySlug, developer_slug: p.developerSlug, project_slug: p.projectSlug ?? null,
  price_aed: p.priceAed, beds: p.beds, baths: p.baths, sqft: p.sqft, handover: p.handover, payment_plan: J(p.paymentPlan ?? null),
  est_yield: p.estYield ?? null, service_charge_per_sqft: p.serviceChargePerSqft ?? null, furnishing: p.furnishing ?? null,
  amenities: p.amenities, images: J(p.images), keywords: p.keywords, lat: p.geo.lat, lng: p.geo.lng, permit: p.permit,
  agent_slug: p.agentSlug, featured: !!p.featured, badge: p.badge ?? null, published: true, published_at: p.publishedAt,
}))
sql += insert("funnels", mock.funnels, (f) => ({
  slug: f.slug, title: J(f.title), pitch: J(f.pitch), key_number: J(f.keyNumber), tag: J(f.tag), external_url: f.externalUrl,
  starts_at: f.startsAt, ends_at: f.endsAt, locales: f.locales === "all" ? null : f.locales, sort_order: f.sortOrder, active: true,
}))
sql += insert("posts", mock.posts, (p) => ({
  slug: p.slug, title: J(p.title), excerpt: J(p.excerpt), body: J(p.body), category: p.category, author: p.author,
  minutes: p.minutes, published: true, published_at: p.publishedAt,
}))
sql += insert("reports", mock.reports, (r) => ({ slug: r.slug, title: J(r.title), quarter: r.quarter, summary: J(r.summary), published: true }))
sql += insert("jobs", mock.jobs, (j) => ({
  slug: j.slug, title: J(j.title), location: j.location, type: J(j.type), summary: J(j.summary), requirements: J(j.requirements), published: true,
}))

writeFileSync(join(root, "supabase", "seed.sql"), sql)
console.log("Wrote supabase/seed.sql")
