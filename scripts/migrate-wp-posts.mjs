#!/usr/bin/env node
// Migrates the blog posts from the old WordPress site (buildcaps.com) into
// supabase/wp-posts.sql, keeping each post's slug so the 301 redirects in
// lib/redirects.mjs (/<slug>/ → /insights/<slug>) land on the same article.
//
//   node scripts/migrate-wp-posts.mjs [https://buildcaps.com] [--update]
//
// Then run the SQL in the Supabase SQL editor (after the migrations).

import { writeFileSync } from "node:fs"
import { join } from "node:path"

const origin = (process.argv.slice(2).find((a) => !a.startsWith("--")) ?? "https://buildcaps.com").replace(/\/$/, "")
const root = join(import.meta.dirname, "..")

const entities = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", rsquo: "’", lsquo: "‘", rdquo: "”", ldquo: "“", ndash: "–", mdash: "—", hellip: "…" }
const decode = (s) =>
  s
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&([a-z]+);/gi, (m, name) => entities[name.toLowerCase()] ?? m)
const strip = (html) => decode(html.replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim()

/** Headings become "## " paragraphs and list items "• " lines; everything else is a paragraph. */
function toParagraphs(html) {
  const clean = html
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\[[^\]]+\]/g, "")
    .replace(/<(script|style|figure|iframe)[\s\S]*?<\/\1>/gi, "")
  const blocks = []
  const re = /<(h[1-6]|p|li|blockquote)[^>]*>([\s\S]*?)<\/\1>/gi
  let m
  while ((m = re.exec(clean))) {
    const text = strip(m[2])
    if (!text) continue
    const tag = m[1].toLowerCase()
    // The old site marks most subheadings as a paragraph that is entirely bold.
    const boldOnly = tag === "p" && /^\s*<(strong|b)>[\s\S]*<\/\1>\s*$/i.test(m[2]) && text.length <= 120 && !/[.:]$/.test(text)
    blocks.push(tag.startsWith("h") || boldOnly ? `## ${text}` : tag === "li" ? `• ${text}` : text)
  }
  // Merge consecutive list items into one block so they read as a list.
  const merged = []
  for (const b of blocks) {
    if (b.startsWith("• ") && merged.length && merged[merged.length - 1].startsWith("• ")) merged[merged.length - 1] += `\n${b}`
    else merged.push(b)
  }
  return merged
}

function category(title) {
  const t = title.toLowerCase()
  if (/off[- ]plan|launch|developments?/.test(t)) return "offPlan"
  if (/communit|location|area|metro|neighbou?rhood/.test(t)) return "communities"
  if (/market|resilien|interest rate|trend|war|price/.test(t)) return "market"
  return "guides"
}

/** First sentences of a paragraph, up to about 280 characters, never cut mid-word. */
function summary(text) {
  if (text.length <= 280) return text
  const sentences = text.match(/[^.!?]+[.!?]+(\s|$)/g) ?? []
  let out = ""
  for (const s of sentences) {
    if ((out + s).length > 280) break
    out += s
  }
  return out.trim() || `${text.slice(0, 277).replace(/\s+\S*$/, "")}…`
}

// --update refreshes posts already imported (excerpt, body, category, length);
// by default existing slugs are left untouched so edits made in the admin survive.
const onConflict = process.argv.includes("--update")
  ? "on conflict (slug) do update set excerpt = excluded.excerpt, body = excluded.body, category = excluded.category, minutes = excluded.minutes"
  : "on conflict (slug) do nothing"

const sql = (v) => (v === null ? "null" : `'${String(v).replace(/'/g, "''")}'`)
const json = (v) => `${sql(JSON.stringify(v))}::jsonb`

const posts = []
for (let page = 1; ; page++) {
  const res = await fetch(`${origin}/wp-json/wp/v2/posts?per_page=100&page=${page}&_fields=slug,date_gmt,title,excerpt,content`, { headers: { "user-agent": "BuildcapsMigration/1.0" } })
  if (!res.ok) break
  const batch = await res.json()
  if (!Array.isArray(batch) || !batch.length) break
  posts.push(...batch)
  if (batch.length < 100) break
}

let out = `-- Blog posts migrated from ${origin} on ${new Date().toISOString().slice(0, 10)} (English).\n-- Generated by scripts/migrate-wp-posts.mjs. Existing slugs are left untouched.\n\n`
for (const p of posts) {
  const title = strip(p.title.rendered)
  const body = toParagraphs(p.content.rendered)
  const words = body.join(" ").split(/\s+/).length
  const excerpt = summary(body.find((b) => !b.startsWith("## ") && !b.startsWith("• ")) ?? strip(p.excerpt.rendered)) || title
  out += `insert into public.posts (slug, title, excerpt, body, category, author, minutes, published, published_at) values (${sql(p.slug)}, ${json({ en: title })}, ${json({ en: excerpt })}, ${json(body.map((b) => ({ en: b })))}, ${sql(category(title))}, 'Buildcaps Research', ${Math.max(2, Math.round(words / 220))}, true, ${sql(p.date_gmt + "Z")}) ${onConflict};\n`
}
writeFileSync(join(root, "supabase", "wp-posts.sql"), out)
writeFileSync(join(root, "lib", "wp-post-slugs.json"), JSON.stringify(posts.map((p) => p.slug).sort(), null, 2) + "\n")
console.log(`${posts.length} posts → supabase/wp-posts.sql, slugs → lib/wp-post-slugs.json`)
